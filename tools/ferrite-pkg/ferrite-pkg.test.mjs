test("durable eval report manifests are evidence, not misplaced consumers", (t) => {
  const ws = workspace();
  t.after(() => rmSync(ws, { recursive: true, force: true }));
  const initial = run(ws, "sync");
  assert.equal(initial.code, 0, initial.out);
  const evidence = join(ws, "evidence", "eval-reports", "run-1", "workspace", "customer-portal");
  const manifest = JSON.stringify({ packages: { "demo-pkg": { mount: "demo" } } }, null, 2);
  const source = "// preserved evaluator output, not a live package copy\npub fn v() -> u32 { 17 }\n";
  write(join(evidence, "ferrite-packages.json"), manifest);
  write(join(evidence, "src", "demo", "mod.rs"), source);

  const checked = run(ws, "check");
  assert.equal(checked.code, 0, checked.out);
  const synced = run(ws, "sync");
  assert.equal(synced.code, 0, synced.out);
  assert.equal(readFileSync(join(evidence, "ferrite-packages.json"), "utf8"), manifest);
  assert.equal(readFileSync(join(evidence, "src", "demo", "mod.rs"), "utf8"), source);
  assert.equal(existsSync(join(evidence, "ferrite-packages.lock.json")), false,
    "sync must not adopt an evidence workspace as a consumer");
  assert.equal(run(ws, "check").code, 0, "the real consumer remains synchronized");
});

