//! Tier-1 readiness artefacts, projected mechanically from the [`Surface`].
//!
//! Each generator is a pure function `&Surface -> String`, so every artefact
//! is deterministic, testable without a fleet, and identical wherever it is
//! served from. These are the "quick win" checks on the industry readiness
//! checklist: robots.txt, sitemap.xml, llms.txt — files most of the web
//! fails to author, generated here as a side effect of declaring the surface.

use crate::agent_ready::surface::{RouteKind, Surface};

/// Well-known paths the readiness face serves. One place, so the server
/// module, the artefacts that cross-reference each other, and the scoring
/// suite agree by construction.
pub mod paths {
    /// Crawler policy.
    pub const ROBOTS: &str = "/robots.txt";
    /// URL inventory.
    pub const SITEMAP: &str = "/sitemap.xml";
    /// The agent orientation file (llmstxt.org).
    pub const LLMS: &str = "/llms.txt";
    /// Expanded corpus: every core page's markdown inline.
    pub const LLMS_FULL: &str = "/llms-full.txt";
    /// Generated OpenAPI 3.1 catalog.
    pub const OPENAPI: &str = "/.well-known/api-catalog";
    /// A2A agent card.
    pub const AGENT_CARD: &str = "/.well-known/agent-card.json";
    /// The MCP endpoint (Streamable HTTP, stateless).
    pub const MCP: &str = "/mcp";
    /// The A2A JSON-RPC endpoint the agent card's `url` names.
    pub const A2A: &str = "/a2a";
    /// MCP registry manifest (static.modelcontextprotocol.io schema).
    pub const MCP_MANIFEST: &str = "/server.json";
    /// MCP server card (well-known discovery twin of the manifest).
    pub const MCP_SERVER_CARD: &str = "/.well-known/mcp/server-card.json";
    /// Agent Skills index (skills.sh / schemas.agentskills.io).
    pub const SKILLS_INDEX: &str = "/.well-known/agent-skills/index.json";
    /// Machine-readable pricing (plain markdown an agent can quote).
    pub const PRICING: &str = "/pricing.md";
    /// The readiness self-report (the platform's own diagnostics shape).
    pub const READINESS: &str = "/.well-known/agent-readiness";
}

/// Project the property's crawler policy without restricting interactive access.
pub fn robots_txt(s: &Surface) -> String {
    let mut out = String::new();
    out.push_str(&format!("# {} — generated by agent-ready\n", s.name));
    out.push_str("# This host is agent-native: see /llms.txt for orientation,\n");
    out.push_str("# /.well-known/api-catalog for the API, /mcp for tools.\n\n");
    // Content Signals (contentsignals.org) declare intent for search, AI input
    // and AI training uses. The line belongs inside the user-agent group it
    // qualifies; a crawler that does not know it ignores it.
    out.push_str("User-agent: *\nContent-Signal: search=yes, ai-input=yes, ai-train=yes\nAllow: /\n\n");
    out.push_str(&format!("Sitemap: {}\n", s.url(paths::SITEMAP)));
    out
}

fn xml_escape(v: &str) -> String {
    v.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
        .replace('\'', "&apos;")
}

/// `(year, month, day)` of a UTC epoch-ms instant (Howard Hinnant's
/// civil-from-days; a constrained app has no date library).
pub(crate) fn civil_date(epoch_ms: u64) -> (i64, i64, i64) {
    let z = (epoch_ms / 86_400_000) as i64 + 719_468;
    let era = z / 146_097;
    let doe = z % 146_097;
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = doy - (153 * mp + 2) / 5 + 1;
    let m = if mp < 10 { mp + 3 } else { mp - 9 };
    let y = yoe + era * 400 + i64::from(m <= 2);
    (y, m, d)
}

fn iso8601_date(epoch_ms: u64) -> String {
    let (y, m, d) = civil_date(epoch_ms);
    format!("{y:04}-{m:02}-{d:02}")
}

/// `sitemap.xml`: every declared page, plus the readiness artefacts agents
/// should discover.
pub fn sitemap_xml(s: &Surface) -> String {
    let mut out = String::from("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n");
    out.push_str("<urlset xmlns=\"http://www.sitemaps.org/schemas/sitemap/0.9\">\n");
    for p in &s.pages {
        out.push_str("  <url>\n");
        out.push_str(&format!("    <loc>{}</loc>\n", xml_escape(&s.url(&p.path))));
        if p.updated_ms > 0 {
            out.push_str(&format!(
                "    <lastmod>{}</lastmod>\n",
                iso8601_date(p.updated_ms)
            ));
        }
        out.push_str("  </url>\n");
    }
    // The orientation artefacts are part of the surface agents should find.
    for path in [paths::LLMS, paths::OPENAPI, paths::AGENT_CARD] {
        out.push_str("  <url>\n");
        out.push_str(&format!("    <loc>{}</loc>\n", xml_escape(&s.url(path))));
        out.push_str("  </url>\n");
    }
    out.push_str("</urlset>\n");
    out
}

/// `llms.txt` (llmstxt.org): H1 title, blockquote summary, sectioned link
/// lists, `Optional` section for non-core pages.
pub fn llms_txt(s: &Surface) -> String {
    let mut out = format!("# {}\n\n> {}\n\n", s.name, s.description);
    let total = s.operations().count();
    let idempotent = s.operations().filter(|o| o.idempotent).count();
    // Retry safety is the host's to implement, so it is advertised exactly
    // as declared: an operation not marked idempotent may run twice.
    let retries = if total > 0 && idempotent == total {
        "Every API operation is declared idempotent: a retry that repeats the \
`idempotency-key` header returns the first result instead of running again."
            .to_string()
    } else if idempotent > 0 {
        format!(
            "{idempotent} of {total} API operations are declared idempotent: a retry that \
repeats the `idempotency-key` header returns the first result. The others may run \
again when retried."
        )
    } else {
        "No API operation is declared idempotent; a retried write may run again.".to_string()
    };
    out.push_str(&format!(
        "Agent-native Ferrite app ({} v{}). {retries} \
Errors are RFC 9457 `application/problem+json`. Content routes serve markdown \
via `Accept: text/markdown` or a `.md` path twin.\n\n",
        s.owner,
        if s.version.is_empty() {
            "0"
        } else {
            &s.version
        }
    ));

    push_pages(&mut out, s, "## Pages\n\n", true);

    let api_routes: Vec<_> = s
        .routes
        .iter()
        .filter(|r| r.kind == RouteKind::Api)
        .collect();
    if !api_routes.is_empty() {
        out.push_str("## API\n\n");
        out.push_str(&format!(
            "- [OpenAPI catalog]({}): every operation with schemas\n",
            s.url(paths::OPENAPI)
        ));
        out.push_str(&format!(
            "- [MCP endpoint]({}): the same operations as callable tools (Streamable HTTP, stateless)\n",
            s.url(paths::MCP)
        ));
        out.push_str(&format!(
            "- [Agent card]({}): identity, skills, and interfaces (A2A)\n",
            s.url(paths::AGENT_CARD)
        ));
        for r in &api_routes {
            for o in &r.operations {
                out.push_str(&format!(
                    "- {} `{} {}`: {}\n",
                    o.name, o.method, o.path, o.description
                ));
            }
        }
        out.push('\n');
    }

    let streams: Vec<_> = s
        .routes
        .iter()
        .filter(|r| matches!(r.kind, RouteKind::Stream | RouteKind::Ws))
        .collect();
    if !streams.is_empty() {
        out.push_str("## Realtime\n\n");
        for r in streams {
            out.push_str(&format!(
                "- `{}` ({}): {}\n",
                r.prefix,
                r.kind.label(),
                r.description
            ));
        }
        out.push('\n');
    }

    push_pages(&mut out, s, "## Optional\n\n", false);
    out
}

fn push_pages(out: &mut String, s: &Surface, heading: &str, core: bool) {
    let pages: Vec<_> = s.pages.iter().filter(|p| p.core == core).collect();
    if pages.is_empty() {
        return;
    }
    out.push_str(heading);
    for p in pages {
        out.push_str(&format!(
            "- [{}]({}): {}\n",
            p.title,
            s.url(&p.path),
            p.summary
        ));
    }
    out.push('\n');
}

/// `llms-full.txt`: llms.txt plus the full markdown of every core page,
/// separated by horizontal rules — the single-fetch corpus shape.
pub fn llms_full_txt(
    s: &Surface,
    page_markdown: &(dyn Fn(&str) -> Option<String> + Sync),
) -> String {
    let mut out = llms_txt(s);
    for p in s.pages.iter().filter(|p| p.core) {
        if let Some(md) = page_markdown(&p.path) {
            out.push_str("\n---\n\n");
            out.push_str(&md);
            if !md.ends_with('\n') {
                out.push('\n');
            }
        }
    }
    out
}

/// `pricing.md`: machine-readable pricing an agent can quote. Projected
/// from the declared operations' `price_micros` — a free product says so
/// in one line, a priced one lists each priced operation with its x402
/// settlement price (1,000,000 micros = $1.00).
pub fn pricing_md(s: &Surface) -> String {
    let mut out = format!("# {} — pricing\n\n", s.name);
    let priced: Vec<_> = s.operations().filter(|o| o.price_micros > 0).collect();
    if priced.is_empty() {
        out.push_str(
            "All operations of this application are **free**: no payment, \
             subscription, or API key is required. Operations declared \
             idempotent return the first result when a retry repeats the \
             `idempotency-key` header.\n",
        );
        return out;
    }
    out.push_str(
        "Priced operations settle per call over [x402](https://www.x402.org). \
         Prices are in USD micros (1,000,000 micros = $1.00). Everything not \
         listed here is free.\n\n| Operation | Price (micros) | Price (USD) |\n|---|---|---|\n",
    );
    for o in &priced {
        out.push_str(&format!(
            "| `{}` | {} | ${:.6} |\n",
            o.name,
            o.price_micros,
            o.price_micros as f64 / 1_000_000.0
        ));
    }
    out
}

/// The one served skill: how an agent uses THIS app. Projected from the
/// surface, so the skill cannot describe operations the app does not have.
pub fn skill_md(s: &Surface) -> String {
    let mut out = format!(
        "---\nname: use-this-app\ndescription: Use the {} API ({}). {}\n---\n\n# Using {}\n\n",
        s.name,
        s.url(""),
        s.description,
        s.name
    );
    out.push_str(&format!(
        "1. Orient at [{llms}]({llms}); the OpenAPI catalog is at [{cat}]({cat}).\n\
         2. Call operations over plain HTTP under the declared routes, or as MCP \
         tools at `{mcp}` (Streamable HTTP, stateless).\n\
         3. Send an `idempotency-key` header on every write. Operations the \
         catalog marks `x-idempotent` return the first admitted result on a \
         replay; retry the others only when a duplicate is acceptable.\n\
         4. Errors are RFC 9457 `application/problem+json`: read `type` for the \
         machine code and `detail` for the human sentence.\n",
        llms = paths::LLMS,
        cat = paths::OPENAPI,
        mcp = paths::MCP,
    ));
    out.push('\n');
    out.push_str(crate::http_change_password::AGENT_GUIDANCE);
    out.push('\n');
    let ops: Vec<_> = s.operations().collect();
    if !ops.is_empty() {
        out.push_str("\n## Operations\n\n");
        for o in ops {
            out.push_str(&format!("- `{}` — {}\n", o.name, o.description));
        }
    }
    out
}

