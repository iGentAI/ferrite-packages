/**
 * The claim the corpus exists for: an app built through the MCP holds the
 * same bytes as one built with `ferrite add`. Every package in this checkout
 * is installed with the real CLI into a scratch app and compared, file by
 * file. Release CI sets `FERRITE_CLI` to its verified installation.
 * Local runs can use an existing build and report a skip if none exists.
 */
test("every package in the corpus is byte-identical to what the real `ferrite add` writes", (t) => {
  const repo = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
  const cli = process.env.FERRITE_CLI ?? [
    join(repo, "tools", "ferrite-cli", "target", "debug", "ferrite"),
    join(repo, "tools", "ferrite-cli", "target", "release", "ferrite"),
  ].find((p) => p && existsSync(p));
  if (cli === undefined) {
    t.skip("no built ferrite CLI (set FERRITE_CLI to the released CLI)");
    return;
  }
  assert.ok(existsSync(cli), `explicit FERRITE_CLI does not exist: ${cli}`);
  const scratch = mkdtempSync(join(realpathSync(tmpdir()), "ferrite-pkg-mcp-"));
  t.after(() => rmSync(scratch, { recursive: true, force: true }));
  const corpus = mcpCorpus(repo, join(scratch, "corpus.json"));
  const registry = JSON.parse(readFileSync(join(repo, "packages/registry.json"), "utf8"));
  const registeredNames = registry.packages.map(pkg => pkg.name).sort();
  assert.ok(registeredNames.length > 0, "the package registry is empty");
  assert.deepEqual(corpus.packages.map(pkg => pkg.name).sort(), registeredNames);
  const home = join(scratch, "home");
  mkdirSync(home);
  let compared = 0;
  for (const pkg of corpus.packages) {
    const app = join(scratch, "apps", pkg.name);
    write(join(app, "Cargo.toml"), '[package]\nname = "x"\nversion = "0.1.0"\nedition = "2021"\n');
    mkdirSync(join(app, "src"), { recursive: true });
    execFileSync(cli, ["add", pkg.name, "--path", repo, "--dir", app], {
      env: { PATH: process.env.PATH, HOME: home, FERRITE_CONFIG: join(home, "credentials.toml") },
      stdio: ["ignore", "pipe", "pipe"],
    });
    const mount = join(app, "src", pkg.root);
    const actualFiles = readdirSync(mount, { recursive: true, withFileTypes: true })
      .filter(entry => !entry.isDirectory())
      .map(entry => relative(mount, join(entry.parentPath, entry.name)).split(sep).join("/"))
      .sort();
    assert.deepEqual(actualFiles, Object.keys(pkg.files).sort(), `${pkg.name}: mounted file inventory`);
    for (const rel of actualFiles) {
      const written = readFileSync(join(mount, rel));
      assert.ok(
        written.equals(Buffer.from(pkg.files[rel], "utf8")),
        `${pkg.name} ${rel}: the corpus differs from ferrite add's copy`,
      );
      compared += 1;
    }
  }
  assert.ok(compared > 300, `compared ${compared} files`);
  t.diagnostic(JSON.stringify({
    binarySha256: createHash("sha256").update(readFileSync(cli)).digest("hex"),
    packages: registeredNames.length,
    comparedFiles: compared,
  }));
});

