/** `check` over `ws`, bounded: a matcher that backtracks is killed and fails the test. */
function checkWithin(ws, timeout) {
  try {
    execFileSync(process.execPath, [TOOL, 'check'], {
      env: { ...process.env, FERRITE_PKG_ROOT: ws },
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
      timeout,
    });
    return { code: 0, out: '' };
  } catch (error) {
    assert.notEqual(error.signal, 'SIGTERM', 'check did not finish: the pattern backtracked');
    return { code: error.status, out: `${error.stdout ?? ''}${error.stderr ?? ''}` };
  }
}

test('a run of stars in one segment matches like one star and cannot hang the matcher', () => {
  // Compiled to a RegExp, 24 stars became 24 adjacent `[^/]*` groups, and a
  // long file name that does not match backtracked for longer than any CI allows.
  const ws = workspace({ hostFiles: [`x${'*'.repeat(24)}y.rs`] });
  run(ws, 'sync');
  write(join(ws, 'app', 'src', 'demo', 'xmidy.rs'), 'pub fn covered() {}\n');
  write(join(ws, 'app', 'src', 'demo', `x${'a'.repeat(48)}.rs`), 'pub fn stray() {}\n');
  const checked = checkWithin(ws, 20_000);
  assert.equal(checked.code, 1, checked.out);
  assert.match(checked.out, new RegExp(`x${'a'.repeat(48)}\\.rs`));
  assert.doesNotMatch(checked.out, /xmidy\.rs/, 'the declared file is covered by the pattern');
  rmSync(ws, { recursive: true, force: true });
});

test('stars separated by a repeated letter cannot hang the matcher', () => {
  // Collapsing adjacent stars does not help here: `*a*a*a*a*a*a*b.rs` compiled
  // to seven `[^/]*` groups split by `a`, and a RegExp engine tries every way
  // of dividing a long run of `a` among them before it can say no -- on the
  // order of n^7 steps for a 240-character name, far past any timeout.
  const pattern = `${'*a'.repeat(6)}*b.rs`;
  const ws = workspace({ hostFiles: [pattern] });
  run(ws, 'sync');
  const stray = `${'a'.repeat(240)}.rs`;
  write(join(ws, 'app', 'src', 'demo', stray), 'pub fn stray() {}\n');
  write(join(ws, 'app', 'src', 'demo', 'xaxaxaxaxaxaxb.rs'), 'pub fn covered() {}\n');
  const started = Date.now();
  const checked = checkWithin(ws, 20_000);
  assert.ok(Date.now() - started < 15_000, 'check took too long for one adversarial name');
  assert.equal(checked.code, 1, checked.out);
  assert.match(checked.out, new RegExp(`${'a'.repeat(240)}\\.rs`), 'the stray file is still reported');
  assert.doesNotMatch(checked.out, /xaxaxaxaxaxaxb\.rs/, 'the declared file is covered by the pattern');
  rmSync(ws, { recursive: true, force: true });
});

