#[cfg(test)]
mod tests {
    use super::*;
    use crate::agent_ready::surface::{Operation, Page, Route, Surface};

    fn surface() -> Surface {
        Surface {
            name: "notes".into(),
            owner: "labs".into(),
            origin: "https://notes.example".into(),
            description: "A note-keeping API.".into(),
            version: "1.0.0".into(),
            routes: vec![Route {
                prefix: "/api/".into(),
                kind: RouteKind::Api,
                description: "notes API".into(),
                operations: vec![Operation {
                    name: "list_notes".into(),
                    method: "GET".into(),
                    path: "/api/notes".into(),
                    description: "List notes.".into(),
                    input_schema: None,
                    output_schema: None,
                    read_only: true,
                    idempotent: true,
                    price_micros: 0,
                }],
            }],
            pages: vec![
                Page {
                    path: "/".into(),
                    title: "Home".into(),
                    summary: "What this is".into(),
                    updated_ms: 1_754_524_800_000, // 2025-08-07? deterministic value
                    core: true,
                },
                Page {
                    path: "/changelog".into(),
                    title: "Changelog".into(),
                    summary: "History".into(),
                    updated_ms: 0,
                    core: false,
                },
            ],
        }
    }

    #[test]
    fn robots_lists_sitemap_and_signals() {
        let r = robots_txt(&surface());
        assert!(r.contains("User-agent: *"));
        assert!(r.contains("Allow: /"));
        assert!(r.contains("Sitemap: https://notes.example/sitemap.xml"));
        assert!(r.contains("Content-Signal:"));
    }

    #[test]
    fn ferrite_hosts_are_open_to_crawlers_like_any_other_origin() {
        for origin in ["https://ferrite.cloud", "https://docs.ferrite.cloud", "https://shop.ferrite.run"] {
            let mut s = surface();
            s.origin = origin.into();
            let text = robots_txt(&s);
            assert!(text.contains("User-agent: *\nContent-Signal: search=yes, ai-input=yes, ai-train=yes\nAllow: /\n"));
            assert!(!text.contains("Disallow"));
            assert!(text.contains(&format!("Sitemap: {origin}/sitemap.xml")));
        }
    }

    #[test]
    fn sitemap_lists_pages_and_wellknown() {
        let x = sitemap_xml(&surface());
        assert!(x.contains("<loc>https://notes.example/</loc>"));
        assert!(x.contains("<loc>https://notes.example/changelog</loc>"));
        assert!(x.contains("<loc>https://notes.example/llms.txt</loc>"));
        assert!(x.contains("<lastmod>"));
        assert!(x.starts_with("<?xml"));
    }

    #[test]
    fn llms_txt_shape() {
        let t = llms_txt(&surface());
        assert!(t.starts_with("# notes\n\n> A note-keeping API.\n"));
        assert!(t.contains("## Pages"));
        assert!(t.contains("## API"));
        assert!(t.contains("list_notes"));
        assert!(t.contains("## Optional"));
        assert!(t.contains("[Changelog](https://notes.example/changelog)"));
    }

    #[test]
    fn llms_txt_advertises_retry_safety_only_as_declared() {
        let mut s = surface();
        assert!(llms_txt(&s).contains("Every API operation is declared idempotent"));
        assert!(!llms_txt(&s).contains("by construction"));
        for o in s.routes.iter_mut().flat_map(|r| r.operations.iter_mut()) {
            o.idempotent = false;
        }
        let t = llms_txt(&s);
        assert!(t.contains("No API operation is declared idempotent"), "{t}");
        assert!(!t.contains("Every API operation"));
    }

    #[test]
    fn llms_full_appends_markdown() {
        let s = surface();
        let f = llms_full_txt(&s, &|path| {
            (path == "/").then(|| "# Home\n\nWelcome.".to_string())
        });
        assert!(f.contains("---\n\n# Home\n\nWelcome."));
    }

    #[test]
    fn date_math() {
        assert_eq!(iso8601_date(0), "1970-01-01");
        assert_eq!(iso8601_date(86_400_000), "1970-01-02");
        assert_eq!(iso8601_date(1_754_524_800_000), "2025-08-07");
    }
}
