// ------------------------------------------------- sync --package (row A04)
//
// 15 November 2026: a ferrite-sso sync in a shared checkout also wrote a
// parallel session's uncommitted Alloy edits into 39 consumers, and an earlier
// scoped sync left packages/registry.json stale. `sync --package` writes only
// the named package's files, lockfile entries and registry entry.

/** Two packages mounted by `app`; `lone` mounts only `other-pkg`. Synced and indexed. */
function twoPackageWorkspace() {
  const ws = workspace();
  write(
    join(ws, "packages", "other-pkg", "ferrite-package.json"),
    JSON.stringify({ name: "other-pkg", version: "1.0.0", root: "other", summary: "s" }, null, 2),
  );
  write(join(ws, "packages", "other-pkg", "src", "mod.rs"), "pub fn o() -> u32 { 1 }\n");
  write(
    join(ws, "app", "ferrite-packages.json"),
    JSON.stringify({ packages: { "demo-pkg": { mount: "demo" }, "other-pkg": { mount: "other" } } }, null, 2),
  );
  write(join(ws, "lone", "ferrite-packages.json"), JSON.stringify({ packages: { "other-pkg": { mount: "other" } } }, null, 2));
  mkdirSync(join(ws, "lone", "src"), { recursive: true });
  assert.equal(run(ws, "sync").code, 0);
  assert.equal(run(ws, "registry").code, 0);
  assert.equal(run(ws, "check").code, 0);
  return ws;
}

const sha = (text) => createHash("sha256").update(text).digest("hex");

test("sync --package writes only that package's copies, lockfile entries and registry entry", () => {
  const ws = twoPackageWorkspace();
  const read = (rel) => readFileSync(join(ws, rel), "utf8");
  const lockBefore = JSON.parse(read("app/ferrite-packages.lock.json"));
  const loneLock = read("lone/ferrite-packages.lock.json");
  const registryBefore = JSON.parse(read("packages/registry.json"));
  // Both packages change; only demo-pkg is synced. other-pkg's edit stands for
  // another session's uncommitted work.
  write(join(ws, "packages", "demo-pkg", "src", "mod.rs"), "pub fn v() -> u32 { 2 }\n");
  write(join(ws, "packages", "other-pkg", "src", "mod.rs"), "pub fn o() -> u32 { 99 }\n");
  const otherCopy = read("app/src/other/mod.rs");

  const synced = run(ws, "sync", "--package", "demo-pkg");
  assert.equal(synced.code, 0, synced.out);
  assert.match(read("app/src/demo/mod.rs"), /\{ 2 \}/);
  assert.equal(read("app/src/other/mod.rs"), otherCopy, "the other package's copy is untouched");
  assert.equal(read("lone/ferrite-packages.lock.json"), loneLock, "a consumer without the package is untouched");
  assert.doesNotMatch(synced.out, /lone/);

  const lock = JSON.parse(read("app/ferrite-packages.lock.json"));
  assert.deepEqual(Object.keys(lock.packages), Object.keys(lockBefore.packages), "entries keep their order");
  assert.deepEqual(lock.packages["other-pkg"], lockBefore.packages["other-pkg"], "other entries are kept byte for byte");
  assert.equal(lock.packages["demo-pkg"].files["mod.rs"], sha(read("app/src/demo/mod.rs")));

  const registry = JSON.parse(read("packages/registry.json"));
  const entry = (index, name) => index.packages.find((p) => p.name === name);
  assert.equal(entry(registry, "demo-pkg").files["mod.rs"], sha(read("packages/demo-pkg/src/mod.rs")), "the synced package is re-indexed");
  assert.deepEqual(entry(registry, "other-pkg"), entry(registryBefore, "other-pkg"), "the other package's index entry is kept");
  assert.equal(registry.serial, registryBefore.serial + 1);

  // What is left is exactly the other package's pending change.
  const checked = run(ws, "check");
  assert.equal(checked.code, 1);
  assert.doesNotMatch(checked.out, /demo/);
  assert.match(checked.out, /app\/src\/other\/mod\.rs: DRIFTED/);
  rmSync(ws, { recursive: true, force: true });
});

test("a scoped sync of an unchanged tree writes the bytes a full sync writes", () => {
  const ws = twoPackageWorkspace();
  const snapshot = () => ["app/ferrite-packages.lock.json", "lone/ferrite-packages.lock.json", "packages/registry.json"]
    .map((rel) => readFileSync(join(ws, rel), "utf8"));
  const before = snapshot();
  const synced = run(ws, "sync", "--package", "other-pkg", "--package", "demo-pkg");
  assert.equal(synced.code, 0, synced.out);
  assert.match(synced.out, /already in sync/);
  assert.match(synced.out, /registry\.json is current/);
  assert.deepEqual(snapshot(), before);
  rmSync(ws, { recursive: true, force: true });
});

test("sync --package narrows to named consumers, and a full sync refreshes the registry", () => {
  const ws = twoPackageWorkspace();
  write(join(ws, "packages", "other-pkg", "src", "mod.rs"), "pub fn o() -> u32 { 3 }\n");
  const scoped = run(ws, "sync", "--package", "other-pkg", "lone");
  assert.equal(scoped.code, 0, scoped.out);
  assert.match(readFileSync(join(ws, "lone/src/other/mod.rs"), "utf8"), /\{ 3 \}/);
  assert.doesNotMatch(readFileSync(join(ws, "app/src/other/mod.rs"), "utf8"), /\{ 3 \}/, "app was not named");
  const full = run(ws, "sync");
  assert.equal(full.code, 0, full.out);
  assert.equal(run(ws, "check").code, 0, "a full sync leaves nothing stale, the registry included");
  rmSync(ws, { recursive: true, force: true });
});

test("sync --package refuses an unknown package and a consumer with no lockfile, naming the fix", () => {
  const ws = twoPackageWorkspace();
  const unknown = run(ws, "sync", "--package", "no-such-pkg");
  assert.equal(unknown.code, 2);
  assert.match(unknown.out, /sync --package no-such-pkg: no such package/);
  assert.equal(run(ws, "sync", "--package").code, 2);
  rmSync(join(ws, "lone", "ferrite-packages.lock.json"));
  write(join(ws, "packages", "other-pkg", "src", "mod.rs"), "pub fn o() -> u32 { 4 }\n");
  const unlocked = run(ws, "sync", "--package", "other-pkg");
  assert.equal(unlocked.code, 2);
  assert.match(unlocked.out, /lone has no ferrite-packages\.lock\.json.*run: node tools\/ferrite-pkg\/ferrite-pkg\.mjs sync lone/);
  assert.doesNotMatch(readFileSync(join(ws, "app/src/other/mod.rs"), "utf8"), /\{ 4 \}/, "the refusal comes before any write");
  rmSync(ws, { recursive: true, force: true });
});
